#!/usr/bin/env python3
"""Corpus benchmark for HexDoku order-bearing 9+9+7 profile.

Reproducible reference configuration:
- CPython 3.10+
- random.Random seed = 20260924
- 500 unique completed Sudoku boards
- boards generated by randomized exact backtracking
- 36 fixed 9+9+7 masks per board
- dynamic minimum-candidate-count target, row-major tie-break
- ascending candidate value with exact feasibility check

The benchmark reports corpus-level K/order-capacity and HR statistics.
It is still a finite experimental corpus, not a universal guarantee.
"""

from __future__ import annotations

from collections import Counter
from itertools import combinations
import json
import math
import random
import statistics
from typing import Dict, List, Sequence, Tuple

from one_board_benchmark import (
    Board,
    FULL,
    bit,
    box_id,
    copy_board,
    iter_digits,
    legal_mask,
    make_997_board,
    put,
    remove,
    solve_order_bearing,
    validate_complete,
)

SEED = 20260924
BOARD_COUNT = 500


def generate_completed_sudoku(rng: random.Random) -> Board:
    board: Board = [[0] * 9 for _ in range(9)]
    row = [0] * 9
    col = [0] * 9
    boxm = [0] * 9

    def rec() -> bool:
        best = None
        best_mask = 0
        best_count = 10

        for r in range(9):
            for c in range(9):
                if board[r][c] != 0:
                    continue

                mask = legal_mask(row, col, boxm, r, c)
                count = mask.bit_count()
                if count == 0:
                    return False

                if count < best_count:
                    best = (r, c)
                    best_mask = mask
                    best_count = count
                    if count == 1:
                        break
            if best_count == 1:
                break

        if best is None:
            return True

        r, c = best
        digits = list(iter_digits(best_mask))
        rng.shuffle(digits)

        for d in digits:
            put(board, row, col, boxm, r, c, d)
            if rec():
                return True
            remove(board, row, col, boxm, r, c, d)

        return False

    if not rec() or not validate_complete(board):
        raise RuntimeError("failed to generate a completed Sudoku")
    return board


def evaluate_parity(parity: Sequence[Sequence[int]]) -> Dict[str, object]:
    threes = [
        (r, c)
        for r in range(9)
        for c in range(9)
        if parity[r][c] == 3
    ]

    accepted = []
    target_hist: Counter[int] = Counter()
    dna_hist: Counter[int] = Counter()

    for visible_pair in combinations(threes, 2):
        masked = make_997_board(parity, visible_pair)
        result = solve_order_bearing(masked)

        if result is None or result["board"] != parity:
            continue

        accepted.append(result)
        target_hist.update(
            {int(k): int(v) for k, v in result["target_hr_hist"].items()}
        )
        dna_hist.update(
            {int(k): int(v) for k, v in result["dna_hr_hist"].items()}
        )

    unique_orders = {
        tuple(result["order"])
        for result in accepted
    }
    k = len(unique_orders)

    return {
        "accepted": len(accepted),
        "K": k,
        "log2K": math.log2(k) if k else 0.0,
        "sum_hr_targets": [int(r["sum_hr_targets"]) for r in accepted],
        "sum_hr_dna": [int(r["sum_hr_dna"]) for r in accepted],
        "feasibility_calls": [int(r["feasibility_calls"]) for r in accepted],
        "candidate_cell_evaluations": sorted(
            {int(r["candidate_cell_evaluations"]) for r in accepted}
        ),
        "target_hist": target_hist,
        "dna_hist": dna_hist,
    }


def main() -> None:
    rng = random.Random(SEED)

    boards: List[Board] = []
    seen = set()

    while len(boards) < BOARD_COUNT:
        board = generate_completed_sudoku(rng)
        key = tuple(cell for row in board for cell in row)
        if key not in seen:
            seen.add(key)
            boards.append(board)

    results = [evaluate_parity(board) for board in boards]
    successful = [r for r in results if int(r["accepted"]) > 0]

    total_masks = BOARD_COUNT * 36
    accepted_masks = sum(int(r["accepted"]) for r in results)

    all_target_hr = Counter()
    all_dna_hr = Counter()
    all_target_sums: List[int] = []
    all_dna_sums: List[int] = []
    all_feasibility: List[int] = []

    for r in results:
        all_target_hr.update(r["target_hist"])
        all_dna_hr.update(r["dna_hist"])
        all_target_sums.extend(r["sum_hr_targets"])
        all_dna_sums.extend(r["sum_hr_dna"])
        all_feasibility.extend(r["feasibility_calls"])

    kvals = [int(r["K"]) for r in results]
    successful_k = [int(r["K"]) for r in successful]
    logvals = [float(r["log2K"]) for r in results]
    successful_logs = [float(r["log2K"]) for r in successful]

    summary = {
        "profile": "sudoku-order-bearing-mrv-v0",
        "hdc_family": "fixed-9+9+7 / 36 masks",
        "generator": "randomized exact Sudoku backtracking",
        "python_rng_seed": SEED,
        "completed_boards": BOARD_COUNT,
        "masks_per_board": 36,
        "masks_tested": total_masks,
        "accepted_exact_roundtrip_masks": accepted_masks,
        "mask_accept_rate": accepted_masks / total_masks,
        "boards_with_at_least_one_mask": len(successful),
        "boards_with_no_valid_mask": BOARD_COUNT - len(successful),
        "board_success_rate": len(successful) / BOARD_COUNT,
        "K_all": {
            "min": min(kvals),
            "mean": statistics.mean(kvals),
            "median": statistics.median(kvals),
            "max": max(kvals),
        },
        "K_successful_boards": {
            "min": min(successful_k),
            "mean": statistics.mean(successful_k),
            "median": statistics.median(successful_k),
            "max": max(successful_k),
        },
        "log2K_all_bits": {
            "min": min(logvals),
            "mean": statistics.mean(logvals),
            "median": statistics.median(logvals),
            "max": max(logvals),
        },
        "log2K_successful_boards_bits": {
            "min": min(successful_logs),
            "mean": statistics.mean(successful_logs),
            "median": statistics.median(successful_logs),
            "max": max(successful_logs),
        },
        "accepted_mask_order_uniqueness": (
            "K == accepted-mask count for every board"
            if all(int(r["K"]) == int(r["accepted"]) for r in results)
            else "some accepted masks share an order"
        ),
        "target_hr_hist": dict(sorted(all_target_hr.items())),
        "full_dna_hr_hist": dict(sorted(all_dna_hr.items())),
        "sum_hr_targets_per_accepted_mask": {
            "min": min(all_target_sums),
            "mean": statistics.mean(all_target_sums),
            "max": max(all_target_sums),
        },
        "sum_hr_dna_per_accepted_mask": {
            "min": min(all_dna_sums),
            "mean": statistics.mean(all_dna_sums),
            "max": max(all_dna_sums),
        },
        "candidate_cell_evaluations_per_accepted_mask": [325],
        "feasibility_calls_per_accepted_mask": {
            "min": min(all_feasibility),
            "mean": statistics.mean(all_feasibility),
            "max": max(all_feasibility),
        },
        "hard_family_order_capacity_upper_bound_bits": math.log2(36),
        "guaranteed_order_capacity_over_this_corpus_bits": (
            min(logvals)
        ),
        "note": (
            "Finite 500-board experimental corpus. A board with no accepted fixed-9+9+7 "
            "mask means the current family needs fallback/expansion; results are not a "
            "universal guarantee for all completed Sudokus."
        ),
    }

    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
